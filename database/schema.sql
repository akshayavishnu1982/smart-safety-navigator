-- Smart Safety Navigator
-- Run this script in Supabase Dashboard > SQL Editor.
-- Public reports are intentionally anonymous in this MVP. For public deployment,
-- add moderation, authentication, abuse controls, and stricter RLS policies.

create table if not exists public.safety_reports (
  id bigint generated by default as identity primary key,
  area text not null check (char_length(trim(area)) between 2 and 120),
  category text not null check (category in (
    'Lighting', 'Road hazard', 'Crowding', 'Helpful resource', 'Other'
  )),
  description text not null check (char_length(trim(description)) between 5 and 1000),
  status text not null default 'published' check (status in ('published', 'hidden')),
  created_at timestamptz not null default now()
);

create index if not exists safety_reports_created_at_idx
  on public.safety_reports (created_at desc);

alter table public.safety_reports enable row level security;

-- Browser clients are not granted direct access. The Express backend uses
-- its server-only key; never put that key in frontend files or GitHub.
revoke all on table public.safety_reports from anon, authenticated;
